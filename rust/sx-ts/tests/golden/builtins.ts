const s = " Hello, World ";
const parts = s.trim().toLowerCase().split(",");
const joined = parts.join("-");
const has = joined.includes("hello");
const idx = [1, 2, 3].indexOf(2);
const sl = joined.slice(1, 3);
const padded = "7".padStart(3, "0");
const r = Math.round(2.5) + Math.floor(1.5) + Math.abs(-3) + Math.max(1, 2) + Math.trunc(-1.5);
const rem = 7 % 3;
const div = 7 / 2;
const num = parseInt("12", 10);
const str = String(num) + (5).toString();
const json = JSON.stringify({ a: 1, b: [1, 2] }, null, 2);
const sorted = [3, 1, 2].map((x) => x).sort((a, b) => b - a);
const names = ["b", "a"].sort();
const entries = Object.fromEntries([["k", 1]]);
const ks = Object.keys(entries).sort();
const cnt = Object.keys(entries).length;
const isArr = Array.isArray(parts);
const t = typeof s === "string";
return { parts, has, idx, sl, padded, r, rem, div, str, json, sorted, names, ks, cnt, isArr, t };
